import Foundation

/// One remembered piece of copied text. Recency is the position in
/// `ClipboardHistory.items`. Old files may carry date fields; decoding
/// ignores them.
public struct ClipboardItem: Identifiable, Codable, Equatable, Sendable {
    public var id: UUID
    public var text: String
    public var isPinned: Bool

    public init(id: UUID = UUID(), text: String, isPinned: Bool = false) {
        self.id = id
        self.text = text
        self.isPinned = isPinned
    }
}

/// Clipboard preferences. They live in `clipboard.json` beside the history,
/// not in `AppSettings`, so the `StorePayload` schema stays untouched.
public struct ClipboardSettings: Codable, Equatable, Sendable {
    public static let defaultCap = 200
    public static let capRange = 10...1000
    /// Choices offered by the UI; any value in `capRange` is still valid.
    public static let capOptions = [50, 100, 200, 500, 1000]

    /// Maximum number of UNPINNED items kept. Pinned items never count.
    public private(set) var cap: Int
    public internal(set) var isPaused: Bool
    /// False until the user accepts the unencrypted-storage notice. Distinct
    /// from `isPaused`, which the user can toggle later.
    public internal(set) var captureEnabled: Bool

    public init(cap: Int = ClipboardSettings.defaultCap, isPaused: Bool = false,
                captureEnabled: Bool = true) {
        self.cap = ClipboardSettings.clamp(cap)
        self.isPaused = isPaused
        self.captureEnabled = captureEnabled
    }

    public mutating func setCap(_ value: Int) {
        cap = ClipboardSettings.clamp(value)
    }

    private static func clamp(_ value: Int) -> Int {
        min(max(value, capRange.lowerBound), capRange.upperBound)
    }

    private enum CodingKeys: String, CodingKey { case cap, isPaused, captureEnabled }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        self.init(cap: try c.decodeIfPresent(Int.self, forKey: .cap) ?? Self.defaultCap,
                  isPaused: try c.decodeIfPresent(Bool.self, forKey: .isPaused) ?? false,
                  captureEnabled: try c.decodeIfPresent(Bool.self, forKey: .captureEnabled) ?? false)
    }
}

/// Text-only clipboard history. `items` is ordered by most recent use,
/// newest first; `displayItems` lifts pinned items above the rest.
public struct ClipboardHistory: Codable, Equatable, Sendable {
    /// Longer text is not remembered, to keep `clipboard.json` small.
    public static let maxTextLength = 100_000

    /// Pasteboard types that mark an item as secret or machine-made
    /// (the nspasteboard.org conventions password managers use).
    public static let skippedTypeIdentifiers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public private(set) var items: [ClipboardItem]
    public private(set) var settings: ClipboardSettings

    public init(items: [ClipboardItem] = [], settings: ClipboardSettings = ClipboardSettings()) {
        self.items = items
        self.settings = settings
        evict()
    }

    /// Pure predicate over the type identifiers present on a pasteboard item.
    public static func shouldCapture(typeIdentifiers: [String]) -> Bool {
        skippedTypeIdentifiers.isDisjoint(with: typeIdentifiers)
    }

    /// Pinned items first, then the rest, each group in recency order.
    public var displayItems: [ClipboardItem] {
        snippets + items.filter { !$0.isPinned }
    }

    /// The pinned items, in recency order. The sidebar Snippets tab lists these.
    public var snippets: [ClipboardItem] {
        items.filter(\.isPinned)
    }

    /// Case- and diacritic-insensitive substring match over `displayItems`.
    public func search(_ query: String) -> [ClipboardItem] {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !q.isEmpty else { return displayItems }
        return displayItems.filter {
            $0.text.range(of: q, options: [.caseInsensitive, .diacriticInsensitive]) != nil
        }
    }

    /// Records copied text. Returns false when nothing changed (paused,
    /// blank or oversized text). Re-copying existing text moves it to the top
    /// and keeps its pin.
    @discardableResult
    public mutating func record(_ text: String) -> Bool {
        guard settings.captureEnabled, !settings.isPaused,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf16.count <= Self.maxTextLength else { return false }
        if let item = items.first(where: { $0.text == text }) {
            moveToTop(item.id)
        } else {
            items.insert(ClipboardItem(text: text), at: 0)
        }
        evict()
        return true
    }

    /// Moves an existing item to the top (the user picked it from the list).
    /// Works while capture is paused.
    public mutating func markUsed(_ id: UUID) {
        moveToTop(id)
    }

    private mutating func moveToTop(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items.insert(items.remove(at: index), at: 0)
    }

    public mutating func setPaused(_ paused: Bool) {
        settings.isPaused = paused
    }

    public mutating func setCaptureEnabled(_ enabled: Bool) {
        settings.captureEnabled = enabled
    }

    /// What a fresh install starts with: nothing is recorded until the user
    /// opts in.
    public static var fresh: ClipboardHistory {
        ClipboardHistory(settings: ClipboardSettings(captureEnabled: false))
    }

    public mutating func setCap(_ cap: Int) {
        settings.setCap(cap)
        evict()
    }

    public mutating func togglePin(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].isPinned.toggle()
        evict()
    }

    public mutating func remove(_ id: UUID) {
        items.removeAll { $0.id == id }
    }

    public mutating func clear(keepPinned: Bool) {
        items = keepPinned ? items.filter(\.isPinned) : []
    }

    /// Drops the least recently used unpinned items beyond the cap.
    private mutating func evict() {
        var unpinned = 0
        items = items.filter { item in
            if item.isPinned { return true }
            unpinned += 1
            return unpinned <= settings.cap
        }
    }

    private enum CodingKeys: String, CodingKey { case items, settings }

    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        let items = try c.decodeIfPresent([Lossy<ClipboardItem>].self, forKey: .items)?
            .compactMap(\.value) ?? []
        var settings = (try? c.decodeIfPresent(ClipboardSettings.self, forKey: .settings))
            ?? ClipboardSettings(captureEnabled: false)
        // Files written before the opt-in existed: history means already enabled.
        let probe = try? c.decodeIfPresent(CaptureEnabledProbe.self, forKey: .settings)
        let hasFlag = probe?.captureEnabled != nil
        if !hasFlag && !items.isEmpty { settings.captureEnabled = true }
        self.init(items: items, settings: settings)
    }
}

private struct CaptureEnabledProbe: Decodable {
    let captureEnabled: Bool?
}

/// Decodes to nil instead of throwing, so one bad array element cannot
/// discard the rest.
private struct Lossy<T: Decodable>: Decodable {
    let value: T?
    init(from decoder: Decoder) throws {
        value = try? T(from: decoder)
    }
}

/// Reads and writes `clipboard.json`, separate from `store.json`.
public enum ClipboardPersistence {
    public static let fileName = "clipboard.json"
    public static let corruptFileName = "clipboard.json.corrupt"

    public static func url(in directory: URL) -> URL {
        directory.appendingPathComponent(fileName)
    }

    /// A missing or unreadable file yields an empty history. A file that
    /// exists but does not decode is moved aside (replacing any earlier
    /// `.corrupt`) so the next save cannot silently overwrite it.
    public static func load(from directory: URL) -> ClipboardHistory {
        let fileURL = url(in: directory)
        guard let data = try? Data(contentsOf: fileURL) else { return .fresh }
        do {
            return try decoder.decode(ClipboardHistory.self, from: data)
        } catch {
            let aside = directory.appendingPathComponent(corruptFileName)
            try? FileManager.default.removeItem(at: aside)
            try? FileManager.default.moveItem(at: fileURL, to: aside)
            return .fresh
        }
    }

    /// The file holds everything the user copied, so it is owner-only. It is
    /// created 0600 from the start (never briefly readable) in a temp file
    /// beside the target and renamed into place.
    @discardableResult
    public static func save(_ history: ClipboardHistory, to directory: URL) -> Bool {
        guard let data = try? encoder.encode(history) else { return false }
        let target = url(in: directory)
        let temp = directory.appendingPathComponent(".\(fileName).\(UUID().uuidString).tmp")
        let fd = open(temp.path, O_WRONLY | O_CREAT | O_EXCL, 0o600)
        guard fd >= 0 else { return false }
        let handle = FileHandle(fileDescriptor: fd, closeOnDealloc: true)
        do {
            try handle.write(contentsOf: data)
            try handle.close()
        } catch {
            try? FileManager.default.removeItem(at: temp)
            return false
        }
        guard rename(temp.path, target.path) == 0 else {
            try? FileManager.default.removeItem(at: temp)
            return false
        }
        return true
    }

    private static var encoder: JSONEncoder {
        let e = JSONEncoder()
        e.dateEncodingStrategy = .iso8601
        e.outputFormatting = [.sortedKeys]
        return e
    }

    private static var decoder: JSONDecoder {
        let d = JSONDecoder()
        d.dateDecodingStrategy = .iso8601
        return d
    }
}
