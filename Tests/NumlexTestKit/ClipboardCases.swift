import Foundation
import NumlexCore

private func tempClipboardDir() throws -> URL {
    let dir = FileManager.default.temporaryDirectory
        .appendingPathComponent("numlex-clip-\(UUID().uuidString)", isDirectory: true)
    try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
    return dir
}

private func texts(_ items: [ClipboardItem]) -> [String] { items.map(\.text) }

public let clipboardCases: [EngineCase] = [

    EngineCase("clipboard-record-puts-newest-first") {
        var h = ClipboardHistory()
        h.record("a"); h.record("b"); h.record("c")
        try expectEqual(texts(h.items), ["c", "b", "a"], "newest first")
    },

    EngineCase("clipboard-dedupe-moves-existing-text-to-top-and-keeps-pin") {
        var h = ClipboardHistory()
        h.record("a"); h.record("b")
        let a = h.items.first { $0.text == "a" }!
        h.togglePin(a.id)
        h.record("a")
        try expectEqual(texts(h.items), ["a", "b"], "a moved to top, no duplicate")
        try expect(h.items[0].isPinned, "pin survives a re-copy")
        try expectEqual(h.items[0].id, a.id, "same item identity")
    },

    EngineCase("clipboard-blank-and-oversized-text-is-ignored") {
        var h = ClipboardHistory()
        try expect(!h.record(" \n\t"), "blank")
        try expect(!h.record(String(repeating: "x", count: ClipboardHistory.maxTextLength + 1)),
                   "oversized")
        try expect(h.items.isEmpty, "nothing recorded")
    },

    EngineCase("clipboard-paused-records-nothing-but-markused-still-works") {
        var h = ClipboardHistory()
        h.record("a"); h.record("b")
        h.setPaused(true)
        try expect(!h.record("c"), "paused capture")
        h.markUsed(h.items[1].id)
        try expectEqual(texts(h.items), ["a", "b"], "markUsed moved a to top")
    },

    EngineCase("clipboard-eviction-keeps-pinned-and-drops-oldest-unpinned") {
        var h = ClipboardHistory(settings: ClipboardSettings(cap: 10))
        h.record("pinned")
        h.togglePin(h.items[0].id)
        for i in 0..<15 { h.record("t\(i)") }
        try expectEqual(h.items.filter { !$0.isPinned }.count, 10, "cap on unpinned only")
        try expect(h.items.contains { $0.text == "pinned" }, "pinned exempt")
        try expect(!h.items.contains { $0.text == "t0" }, "oldest unpinned evicted")
        try expect(h.items.contains { $0.text == "t14" }, "newest kept")
    },

    EngineCase("clipboard-lowering-cap-evicts-and-cap-is-clamped") {
        var h = ClipboardHistory()
        for i in 0..<30 { h.record("t\(i)") }
        h.setCap(10)
        try expectEqual(h.items.count, 10, "evicted on cap change")
        h.setCap(1)
        try expectEqual(h.settings.cap, ClipboardSettings.capRange.lowerBound, "clamped low")
    },

    EngineCase("clipboard-unpinning-reapplies-cap") {
        var h = ClipboardHistory(settings: ClipboardSettings(cap: 10))
        h.record("old")
        h.togglePin(h.items[0].id)
        for i in 0..<10 { h.record("t\(i)") }
        try expectEqual(h.items.count, 11, "10 unpinned plus 1 pinned")
        h.togglePin(h.items.first { $0.text == "old" }!.id)
        try expectEqual(h.items.count, 10, "old is now the oldest unpinned and is evicted")
    },

    EngineCase("clipboard-display-order-is-pinned-first") {
        var h = ClipboardHistory()
        h.record("a"); h.record("b"); h.record("c")
        h.togglePin(h.items.first { $0.text == "a" }!.id)
        try expectEqual(texts(h.displayItems), ["a", "c", "b"], "pinned first, then recency")
    },

    EngineCase("clipboard-search-is-case-and-diacritic-insensitive") {
        var h = ClipboardHistory()
        h.record("Café total = 42"); h.record("other"); h.record("TOTAL 7")
        try expectEqual(texts(h.search("cafe")), ["Café total = 42"], "diacritics")
        try expectEqual(Set(texts(h.search("total"))), ["Café total = 42", "TOTAL 7"], "case")
        try expectEqual(h.search("  ").count, 3, "blank query lists everything")
        try expectEqual(h.search("zzz").count, 0, "no match")
    },

    EngineCase("clipboard-remove-and-clear") {
        var h = ClipboardHistory()
        h.record("a"); h.record("b"); h.record("c")
        h.remove(h.items[0].id)
        try expectEqual(texts(h.items), ["b", "a"], "removed c")
        h.togglePin(h.items[0].id)
        h.clear(keepPinned: true)
        try expectEqual(texts(h.items), ["b"], "pinned survives")
        h.clear(keepPinned: false)
        try expect(h.items.isEmpty, "all gone")
    },

    EngineCase("clipboard-concealed-types-are-not-captured") {
        try expect(ClipboardHistory.shouldCapture(typeIdentifiers: ["public.utf8-plain-text"]),
                   "plain text")
        for marker in ["Concealed", "Transient", "AutoGenerated"] {
            try expect(!ClipboardHistory.shouldCapture(
                typeIdentifiers: ["public.utf8-plain-text", "org.nspasteboard.\(marker)Type"]),
                       "\(marker) items are skipped")
        }
    },

    EngineCase("clipboard-codable-round-trip-and-separate-file") {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("numlex-clip-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: dir) }
        var h = ClipboardHistory(settings: ClipboardSettings(cap: 50, isPaused: false))
        h.record("hello")
        h.record("world")
        h.togglePin(h.items[1].id)
        try expect(ClipboardPersistence.save(h, to: dir), "saved")
        try expectEqual(ClipboardPersistence.load(from: dir), h, "round trip")
        try expectEqual(try FileManager.default.contentsOfDirectory(atPath: dir.path),
                        ["clipboard.json"], "only clipboard.json written, store.json untouched")
    },

    EngineCase("clipboard-missing-file-loads-empty") {
        let dir = try tempClipboardDir()
        defer { try? FileManager.default.removeItem(at: dir) }
        try expectEqual(ClipboardPersistence.load(from: dir), .fresh, "missing")
    },

    EngineCase("clipboard-corrupt-file-is-moved-aside-and-replaces-old-corrupt") {
        let dir = try tempClipboardDir()
        defer { try? FileManager.default.removeItem(at: dir) }
        let aside = dir.appendingPathComponent(ClipboardPersistence.corruptFileName)
        try Data([9, 9]).write(to: aside)
        try Data([0, 1, 2]).write(to: ClipboardPersistence.url(in: dir))
        try expectEqual(ClipboardPersistence.load(from: dir), .fresh, "empty start")
        try expect(!FileManager.default.fileExists(atPath: ClipboardPersistence.url(in: dir).path),
                   "original moved away")
        try expectEqual(try Data(contentsOf: aside), Data([0, 1, 2]), "latest corrupt copy kept")
    },

    EngineCase("clipboard-one-bad-element-keeps-the-rest-including-pins") {
        let dir = try tempClipboardDir()
        defer { try? FileManager.default.removeItem(at: dir) }
        let a = "00000000-0000-0000-0000-00000000000A"
        let c = "00000000-0000-0000-0000-00000000000C"
        let json = "{\"items\":[{\"id\":\"" + a + "\",\"text\":\"a\",\"isPinned\":true},"
            + "{\"id\":\"nope\",\"text\":5},"
            + "{\"id\":\"" + c + "\",\"text\":\"c\",\"isPinned\":false}]}"
        try Data(json.utf8).write(to: ClipboardPersistence.url(in: dir))
        let h = ClipboardPersistence.load(from: dir)
        try expectEqual(texts(h.items), ["a", "c"], "good elements kept")
        try expect(h.items[0].isPinned, "pin kept")
        try expect(!FileManager.default.fileExists(atPath:
            dir.appendingPathComponent(ClipboardPersistence.corruptFileName).path), "not treated as corrupt")
    },

    EngineCase("clipboard-file-is-owner-only-including-after-overwrite") {
        let dir = try tempClipboardDir()
        defer { try? FileManager.default.removeItem(at: dir) }
        var h = ClipboardHistory()
        h.record("secret")
        try expect(ClipboardPersistence.save(h, to: dir), "first save")
        h.record("more")
        try expect(ClipboardPersistence.save(h, to: dir), "overwrite")
        let attrs = try FileManager.default.attributesOfItem(atPath: ClipboardPersistence.url(in: dir).path)
        try expectEqual((attrs[.posixPermissions] as? NSNumber)?.intValue, 0o600, "0600")
        try expectEqual(try FileManager.default.contentsOfDirectory(atPath: dir.path),
                        ["clipboard.json"], "no temp file left")
    },

    EngineCase("clipboard-old-files-with-date-fields-still-load") {
        let id = "00000000-0000-0000-0000-000000000001"
        let data = Data(("{\"items\":[{\"id\":\"" + id + "\",\"text\":\"a\","
            + "\"createdAt\":\"2024-01-01T00:00:00Z\",\"lastUsedAt\":\"2024-01-02T00:00:00Z\","
            + "\"isPinned\":true}]}").utf8)
        let h = try JSONDecoder().decode(ClipboardHistory.self, from: data)
        try expectEqual(texts(h.items), ["a"], "item kept")
        try expect(h.items[0].isPinned, "pin kept")
    },

    EngineCase("clipboard-settings-decode-tolerates-missing-fields") {
        let data = Data(#"{"items":[]}"#.utf8)
        let h = try JSONDecoder().decode(ClipboardHistory.self, from: data)
        try expectEqual(h.settings, ClipboardSettings(captureEnabled: false), "defaults, capture off")
    },

    EngineCase("clipboard-fresh-install-records-nothing-until-enabled") {
        let dir = try tempClipboardDir()
        defer { try? FileManager.default.removeItem(at: dir) }
        var h = ClipboardPersistence.load(from: dir)
        try expect(!h.settings.captureEnabled, "off by default")
        try expect(!h.record("a"), "nothing recorded")
        h.setCaptureEnabled(true)
        try expect(h.record("a"), "recorded once enabled")
        try expect(ClipboardPersistence.save(h, to: dir), "save")
        try expect(ClipboardPersistence.load(from: dir).settings.captureEnabled, "choice persists")
    },

    EngineCase("clipboard-old-file-without-flag-loads-enabled-when-it-has-items") {
        let dir = try tempClipboardDir()
        defer { try? FileManager.default.removeItem(at: dir) }
        let id = "00000000-0000-0000-0000-000000000001"
        let withItems = "{\"items\":[{\"id\":\"" + id + "\",\"text\":\"a\",\"isPinned\":false}],"
            + "\"settings\":{\"cap\":50,\"isPaused\":false}}"
        try Data(withItems.utf8).write(to: ClipboardPersistence.url(in: dir))
        let h = ClipboardPersistence.load(from: dir)
        try expect(h.settings.captureEnabled, "history present means already enabled")
        try expectEqual(h.settings.cap, 50, "other settings kept")
        let empty = Data(#"{"items":[],"settings":{"cap":50}}"#.utf8)
        let emptyHistory = try JSONDecoder().decode(ClipboardHistory.self, from: empty)
        try expect(!emptyHistory.settings.captureEnabled, "no history means the notice still shows")
    },
]

public let clipboardInsertionCases: [EngineCase] = [

    EngineCase("clipboard-insert-appends-as-new-line") {
        let p = ClipboardInsertion.appendPlan(content: "1 + 1", text: "2 * 3")
        try expectEqual(p?.content, "1 + 1\n2 * 3", "new line")
        try expectEqual(p?.edit, NotebookEdit(range: NSRange(location: 5, length: 0), replacement: "\n2 * 3"),
                        "edit at the end")
        try expectEqual(p?.caret, 11, "caret after the new text")
    },

    EngineCase("clipboard-insert-fills-trailing-empty-line-and-empty-sheet") {
        try expectEqual(ClipboardInsertion.appendPlan(content: "a\n", text: "b")?.content, "a\nb",
                        "trailing empty line is reused")
        try expectEqual(ClipboardInsertion.appendPlan(content: "", text: "b")?.content, "b",
                        "empty sheet")
    },

    EngineCase("clipboard-insert-normalizes-text") {
        let p = ClipboardInsertion.appendPlan(content: "x", text: "a\u{FFFC}b\r\nc\n\n")
        try expectEqual(p?.content, "x\nab\nc", "marker stripped, CRLF folded, trailing newlines trimmed")
    },

    EngineCase("clipboard-insert-nothing-yields-no-plan") {
        try expect(ClipboardInsertion.appendPlan(content: "x\n", text: "\n\u{FFFC}") == nil, "empty after cleaning")
    },
]

public let clipboardLocalizationCases: [EngineCase] = [
    EngineCase("clipboard-strings-exist-in-all-six-locales") {
        let keys = L10n.translations[.en]!.keys.filter { $0.hasPrefix("clipboard.") }
        try expect(!keys.isEmpty, "english clipboard keys present")
        for language in AppLanguage.allCases {
            for key in keys {
                let value = L10n.translations[language]?[key] ?? ""
                try expect(!value.isEmpty, "\(language) is missing \(key)")
            }
        }
        try expectEqual(L10n.t("clipboard.title", language: .zh), "剪贴板", "zh title")
    },
]
